def 글자정리(text) -> str:
    """비교하기 쉽도록 공백·쉼표·따옴표·기호를 모두 지웁니다."""
    return re.sub(r"[\s,\"'·ㆍ/\\\-~]", "", str(text))


# 각 섹션의 key(내부 이름), title(화면 표시용), patterns(제목 줄을 알아보는 단서)
SECTIONS = [
    {
        "key": "longest",
        "title": "가장 긴 폭염",
        "patterns": ("가장긴폭염",),
    },
    {
        "key": "early_late",
        "title": "가장 빠른/가장 늦은 폭염",
        "patterns": ("가장빠른가장늦은폭염", "가장이른가장늦은폭염", "가장빠른폭염"),
    },
    {
        "key": "daily",
        "title": "전국 폭염일수",
        "patterns": ("전국폭염일수",),
    },
]


@st.cache_data(show_spinner="heatwave.csv 를 읽는 중입니다...")
def csv_원문_읽기(path: str) -> str:
    """
    파일을 글자로 읽어옵니다.
    한글 CSV는 인코딩이 제각각이라 utf-8 → cp949 순서로 시도합니다.
    """
    파일 = Path(path)
    if not 파일.exists():
        raise FileNotFoundError(path)

    for 인코딩 in ("utf-8-sig", "utf-8", "cp949", "euc-kr"):
        try:
            return 파일.read_text(encoding=인코딩)
        except UnicodeDecodeError:
            continue  # 실패하면 다음 인코딩으로 다시 시도
    # 그래도 안 되면 깨진 글자는 무시하고 읽기
    return 파일.read_text(encoding="cp949", errors="ignore")


def 섹션_나누기(원문: str) -> dict:
    """
    한 파일 안에 들어 있는 표 3개를 찾아 각각 데이터프레임으로 만듭니다.
    반환값 예시: {"longest": df1, "early_late": df2, "daily": df3}
    """
    줄들 = 원문.splitlines()

    # (1) 제목 줄이 몇 번째 줄인지 찾기 - 첫 칸이 제목과 똑같은 줄을 찾습니다.
    표시 = []
    for i, 줄 in enumerate(줄들):
        첫칸 = 글자정리(줄.split(",")[0])
        전체 = 글자정리(줄)
        for 섹션 in SECTIONS:
            if 첫칸 in 섹션["patterns"] or 전체 in 섹션["patterns"]:
                표시.append((i, 섹션["key"]))
                break

    # (2) 못 찾은 섹션이 있으면 "○○로 시작하는 줄"로 한 번 더 느슨하게 찾기
    찾은키 = {키 for _, 키 in 표시}
    for 섹션 in SECTIONS:
        if 섹션["key"] in 찾은키:
            continue
        for i, 줄 in enumerate(줄들):
            첫칸 = 글자정리(줄.split(",")[0])
            if 첫칸 and any(첫칸.startswith(p[:5]) for p in 섹션["patterns"]):
                표시.append((i, 섹션["key"]))
                break
    표시.sort()

    # (3) 제목 줄 다음부터 그 다음 제목 줄 전까지를 하나의 표로 읽기
    결과 = {}
    for 순번, (시작, 키) in enumerate(표시):
        끝 = 표시[순번 + 1][0] if 순번 + 1 < len(표시) else len(줄들)
        덩어리 = [줄 for 줄 in 줄들[시작 + 1 : 끝] if 글자정리(줄) != ""]
        if not 덩어리:
            continue
        df = pd.read_csv(io.StringIO("\n".join(덩어리)), engine="python", skip_blank_lines=True)
        df = df.dropna(axis=1, how="all").dropna(how="all")      # 완전히 빈 행·열 제거
        df.columns = [str(c).strip() for c in df.columns]        # 열 이름 앞뒤 공백 제거
        결과[키] = df.reset_index(drop=True)
    return 결과


def 열_찾기(df: pd.DataFrame, 후보들) -> str | None:
    """'년도', '연도' 처럼 이름이 조금씩 다를 수 있으니 비슷한 열 이름을 찾아줍니다."""
    for 후보 in 후보들:                       # 먼저 완전히 같은 이름을 찾고
        for 열 in df.columns:
            if 글자정리(열) == 글자정리(후보):
                return 열
    for 후보 in 후보들:                       # 없으면 포함되는 이름을 찾습니다
        for 열 in df.columns:
            if 글자정리(후보) in 글자정리(열):
                return 열
    return None


@st.cache_data(show_spinner=False)
def 폭염일수_표_만들기(원자료: pd.DataFrame) -> pd.DataFrame:
    """
    '전국 폭염일수' 원자료(년도·날짜·지점)를 받아
    [년도, 지점, 폭염일수] 형태의 표로 정리합니다.
    """
    년도열 = 열_찾기(원자료, ["년도", "연도", "year"])
    날짜열 = 열_찾기(원자료, ["날짜", "일자", "date"])
    지점열 = 열_찾기(원자료, ["지점", "지점명", "관측지점", "station"])

    if 지점열 is None or (날짜열 is None and 년도열 is None):
        raise ValueError("'전국 폭염일수' 표에서 지점/날짜 열을 찾지 못했습니다.")

    d = 원자료.copy()
    d["지점"] = d[지점열].astype(str).str.strip()

    # 날짜 문자열을 날짜형으로 바꿉니다(형식이 이상하면 비워 둠).
    d["날짜"] = pd.to_datetime(d[날짜열], errors="coerce") if 날짜열 else pd.NaT

    if 년도열:
        d["년도"] = pd.to_numeric(d[년도열], errors="coerce")
    else:
        d["년도"] = d["날짜"].dt.year

    # 날짜 변환이 실패한 줄은 원래 글자를 그대로 써서 같은 날을 중복으로 세지 않게 합니다.
    d["_날짜키"] = d["날짜"].astype(str)
    if 날짜열:
        빈칸 = d["날짜"].isna()
        d.loc[빈칸, "_날짜키"] = d.loc[빈칸, 날짜열].astype(str)

    d = d.dropna(subset=["년도"])
    d = d[d["지점"].str.len() > 0]
    d["년도"] = d["년도"].astype(int)

    # 같은 (년도, 지점)에서 서로 다른 날짜의 개수 = 그 해의 폭염일수
    표 = (
        d.groupby(["년도", "지점"])["_날짜키"]
        .nunique()
        .reset_index(name="폭염일수")
        .sort_values(["년도", "폭염일수"], ascending=[True, False])
    )
    return 표


